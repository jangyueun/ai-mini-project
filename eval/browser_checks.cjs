// 완료된 대화의 새로고침 복원·세션 분리·후속 선택을 실제 브라우저로 확인한다.
const {chromium}=require('playwright');
const fs=require('fs');
const assert=require('assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL || 'chrome'});
 const context=await browser.newContext({viewport:{width:1280,height:1000}});
 const page=await context.newPage();
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 const checks=[];
 const screen=async name=>page.screenshot({path:`doc/evidence/${name}.png`,fullPage:false});
 const submit=async text=>{
  await page.getByRole('textbox',{name:'질문',exact:true}).fill(text);
  await page.getByRole('button',{name:'보내기',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('form button').disabled,{timeout:45000});
 };
 // 개선 전은 같은 입력을 기본 화면에 넣고 새로고침 결과를 캡처한다.
 await page.goto('http://127.0.0.1:8861');
 await page.locator('input').waitFor();
 await page.locator('input').fill('payments-service CPU 급증 원인 진단해줘');
 await page.getByRole('button',{name:'보내기'}).click();
 await page.waitForFunction(()=>!document.querySelector('form button').disabled);
 await screen('before-01-conversation');
 await page.reload(); await page.locator('input').waitFor();
 checks.push({case:'개선 전 새로고침 후 메시지 수',actual:await page.locator('.bubble').count()});
 await screen('before-02-refresh-lost');
 await page.goto('http://127.0.0.1:8860');
 await page.getByRole('textbox',{name:'질문',exact:true}).waitFor({state:'visible'});
 await page.waitForFunction(()=>!document.querySelector('form button').disabled);
 await submit('payments-service CPU 급증 원인 진단해줘');
 const thread1=await page.locator('select').inputValue();
 await page.reload();
 await page.waitForFunction(()=>!document.querySelector('form button').disabled);
 assert.equal(await page.locator('.bubble').count(),2);
 assert.equal(await page.locator('select').inputValue(),thread1);
 assert.match(await page.locator('.context').innerText(),/payments-service/);
 checks.push({case:'새로고침 후 메시지·대상 복원',pass:true});
 await screen('after-01-restored');
 await submit('그 서비스 다시 확인해줘');
 assert.match(await page.locator('#log').innerText(),/이전 조사 대상 연결: payments-service/);
 assert.match(await page.locator('#log').innerText(),/CPU 90.2%/);
 checks.push({case:'후속 요청의 새 데이터 확인',pass:true});
 await screen('after-02-followup');
 await page.getByRole('button',{name:'＋ 새 대화 시작',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('form button').disabled);
 const thread2=await page.locator('select').inputValue(); assert.notEqual(thread1,thread2);
 await submit('그 서비스 다시 확인해줘');
 assert.match(await page.locator('#log').innerText(),/이전 조사 대상이 없어요/);
 checks.push({case:'새 대화에 이전 대상 유입 없음',pass:true});
 await screen('after-03-new-conversation');
 await page.getByRole('button',{name:'＋ 새 대화 시작',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('form button').disabled);
 await submit('payments-service cache-service 장애 진단해줘');
 await submit('그 서비스 다시 확인해줘');
 assert.equal(await page.locator('.candidates button').count(),2);
 await screen('after-04-clarification');
 await page.locator('.candidates').getByRole('button',{name:'cache-service',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('form button').disabled);
 assert.match(await page.locator('.context').innerText(),/^최근 조사 대상: cache-service/);
 checks.push({case:'복수 대상 확인 및 선택 후 재진단',pass:true});
 await screen('after-05-selection');
 await page.locator('select').selectOption(thread1);
 await page.waitForFunction(()=>!document.querySelector('form button').disabled);
 assert.equal(await page.locator('.bubble').count(),4);
 checks.push({case:'이전 대화 선택 및 복원',pass:true});
 page.once('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'현재 대화 기록 삭제',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.notice').textContent.includes('삭제했어요'));
 assert.equal(await page.locator('.bubble').count(),0);
 await page.locator('select').selectOption(thread2);
 await page.waitForFunction(()=>!document.querySelector('form button').disabled);
 assert.equal(await page.locator('.bubble').count(),2);
 checks.push({case:'현재 대화만 명시적 삭제',pass:true});
 await page.getByRole('button',{name:'＋ 새 대화 시작',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('form button').disabled);
 await submit('payments-service CPU 급증 원인 진단해줘');
 await submit('billing-service 다시 확인해줘');
 await submit('그 서비스 다시 확인해줘');
 assert.match(await page.locator('.bubble').last().innerText(),/아직 조회할 대상이 정해지지/);
 assert.doesNotMatch(await page.locator('.steps').last().innerText(),/모니터링 새로 조회/);
 checks.push({case:'미등록 대상 확인 대기 중 과거 대상 재사용 차단',pass:true});
 await screen('after-07-pending-safe');
 await submit('그 서비스 다시 확인하지 마');
 assert.match(await page.locator('.bubble').last().innerText(),/취소/);
 assert.equal(await page.locator('.candidates button').count(),0);
 assert.doesNotMatch(await page.locator('.steps').last().innerText(),/모니터링 새로 조회/);
 checks.push({case:'부정 요청의 도구 호출 차단·확인 대기 해제',pass:true});
 await screen('after-08-cancelled');
 await submit('payments-service 말고 cache-service 다시 확인해줘');
 assert.match(await page.locator('.context').innerText(),/^최근 조사 대상: cache-service/);
 assert.doesNotMatch(await page.locator('.steps').last().innerText(),/모니터링 새로 조회: payments-service/);
 checks.push({case:'제외한 서비스 미조회·선택 대상만 신규 조회',pass:true});
 await screen('after-09-excluded-target');
 await submit('그 서비스가 뭔지 설명해줘');
 assert.doesNotMatch(await page.locator('.steps').last().innerText(),/모니터링 새로 조회/);
 checks.push({case:'설명 요청의 불필요한 진단 차단',pass:true});
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
 await screen('after-06-mobile');
 assert.deepEqual(errors,[]);
 fs.writeFileSync('eval/browser_results.json',JSON.stringify({mode:'Chromium + fake LLM + recording MCP',checks,page_errors:errors},null,2));
 console.log(JSON.stringify(checks));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
